"""Builds every SVG in assets/ from source.

    pip install -r assets/src/requirements.txt
    python assets/src/build.py            # all assets
    python assets/src/build.py hero       # just one

The telemetry console is not built here: .github/scripts/telemetry.mjs renders it
from live GitHub data (this script only refreshes the glyph atlas it uses).
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
OUT = os.path.dirname(HERE)

import hero  # noqa: E402
import sections  # noqa: E402

ATLAS = os.path.join(os.path.dirname(OUT), ".github", "scripts", "glyphs.json")
ATLAS_FONTS = [("sora", 700), ("manrope", 600), ("mono", 500), ("mono", 600)]
ATLAS_CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "·—°"


def atlas():
    """Glyph outlines for .github/scripts/telemetry.mjs, which renders text without any npm packages."""
    import json
    from svgkit import Font
    fonts = {}
    for family, weight in ATLAS_FONTS:
        f = Font.get(family, weight)
        glyphs = {}
        for ch in ATLAS_CHARS:
            gname, adv, _, _ = f.shape(ch)[0]
            glyphs[ch] = [adv, f.path(gname)]
        fonts[f.key] = {"upm": f.upm, "glyphs": glyphs}
    data = json.dumps({"note": "Generated by assets/src/build.py atlas. Sora, Manrope and JetBrains Mono (SIL OFL 1.1).",
                       "fonts": fonts}, separators=(",", ":"))
    with open(ATLAS, "w", encoding="utf-8") as fh:
        fh.write(data)
    return len(data)


TARGETS = {
    "hero": lambda: hero.build(os.path.join(OUT, "hero.svg")),
    "atlas": atlas,
    **{name: (lambda fn=fn, name=name: fn(os.path.join(OUT, f"{name}.svg")))
       for name, fn in sections.TARGETS.items()},
}

if __name__ == "__main__":
    wanted = sys.argv[1:] or list(TARGETS)
    for name in wanted:
        size = TARGETS[name]()
        if isinstance(size, dict):
            for k, v in size.items():
                print(f"{k:<28} {v / 1024:6.1f} KB")
        else:
            label = "glyphs.json" if name == "atlas" else name + ".svg"
            print(f"{label:<28} {size / 1024:6.1f} KB")
